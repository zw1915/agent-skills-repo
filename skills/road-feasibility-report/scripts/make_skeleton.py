#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
道路工程可行性研究报告骨架生成器（road-feasibility-report 技能配套脚本）

依据：发改投资规〔2023〕304号《政府投资项目可行性研究报告编写通用大纲（2023年版）》十章结构，
并注入道路工程专业提示。生成带全部章节标题与【撰写提示】的 Markdown 骨架，确保成稿零遗漏。

用法：
  python make_skeleton.py --name "XX 公路改建工程" --out report.md
  python make_skeleton.py --name "XX 市政道路工程"            # 输出到 stdout
"""
import argparse
import sys


def h1(t):
    return f"\n# {t}\n"


def h2(t):
    return f"\n## {t}\n"


def h3(t):
    return f"\n### {t}\n"


def para(text):
    return f"{text}\n"


def build(name: str) -> str:
    n = name or "XX 道路/公路工程"
    out = []
    out.append(f"# {n} 工程可行性研究报告\n")
    out.append("> 编制依据：《政府投资项目可行性研究报告编写通用大纲（2023年版）》（发改投资规〔2023〕304号，2023-05-01 施行）。\n")
    out.append("> 本文件为骨架草稿，括号内【】为撰写提示，请逐项替换为真实内容；缺失信息保留【待补充：……】。\n")

    # 一、概述
    out.append(h1("一、概述"))
    out.append(h2("（一）项目概况"))
    out.append(para("【待补充：项目全称及简称；建设目标与任务；建设地点；里程/等级/车道数/路基宽度/设计速度/桥隧数量等主要产出；建设工期；总投资与资金来源；建设模式；主要技术经济指标；绩效目标】"))
    out.append(h2("（二）项目单位概况"))
    out.append(para("【待补充：项目单位基本情况；拟新组建项目法人的组建方案；政府资本金注入项目的法人信息、投资人构成及政府出资人代表】"))
    out.append(h2("（三）编制依据"))
    out.append(para("【待补充：项目建议书及批复；国家/地方支持性规划；产业政策与行业准入；主要标准规范（JTG B01 等）；专题研究成果】"))
    out.append(h2("（四）主要结论和建议"))
    out.append(para("【待补充：可研主要结论（推荐路线、技术标准、投资匡算、经济评价结论）与核心建议】"))

    # 二、项目建设背景和必要性
    out.append(h1("二、项目建设背景和必要性"))
    out.append(h2("（一）项目建设背景"))
    out.append(para("【待补充：立项背景；用地预审、规划选址等审批手续进展；其他前期工作进展】"))
    out.append(h2("（二）规划政策符合性"))
    out.append(para("【待补充：与国民经济/区域/专项/国土空间规划的衔接；与扩大内需、乡村振兴、双碳、国家安全等重大政策的符合性；在综合立体交通网中的功能定位】"))
    out.append(h2("（三）项目建设必要性"))
    out.append(para("【待补充：从战略/规划、产业政策、经济社会发展、履职尽责层面论证必要性与建设时机；缓解瓶颈、改善出行、支撑产业/旅游/城镇化】"))

    # 三、项目需求分析与产出方案
    out.append(h1("三、项目需求分析与产出方案"))
    out.append(h2("（一）需求分析"))
    out.append(para("【道路专项：做交通量预测——OD 调查、四阶段法、预测特征年（20年）、分客车/货车；弹性系数须基于历史与规划确定且不大于规划值；通道交通量考虑并行铁路分流】"))
    out.append(h2("（二）建设内容和规模"))
    out.append(para("【待补充：路线走向、主要控制点、里程、公路等级、车道数、路基宽度、设计速度、桥隧规模、连接线/立交；分期项目近远期安排】"))
    out.append(h2("（三）项目产出方案"))
    out.append(para("【待补充：正常运营年应达到的通行能力/服务水平及质量标准，评价产出合理性】"))

    # 四、项目选址与要素保障
    out.append(h1("四、项目选址与要素保障"))
    out.append(h2("（一）项目选址或选线"))
    out.append(para("【道路专项：走廊带多方案比选与起终点论证；明确土地权属、供地方式、占用耕地/永久基本农田/生态保护红线、矿产压覆、地灾评估】"))
    out.append(h2("（二）项目建设条件"))
    out.append(para("【待补充：自然环境（地形/气象/水文/地质/地震/防洪）、交通运输、公用工程（水电气热通信消防）；施工与依托条件；改扩建分析现有设施】"))
    out.append(h2("（三）要素保障分析"))
    out.append(para("【待补充：土地要素（国土空间规划符合性、用地指标、占补平衡、永农补划）；资源环境要素（水资源/能源/生态承载力、能耗/碳排放/减排约束）】"))

    # 五、项目建设方案（核心）
    out.append(h1("五、项目建设方案"))
    out.append(h2("（一）技术方案 / 技术标准"))
    out.append(para("【道路专项：依据 JTG B01 确定公路等级、设计速度、路基宽度、车道数、荷载等级、设计洪水频率；简述推荐技术路线理由】"))
    out.append(h2("（二）设备方案"))
    out.append(para("【待补充：施工设备与运营养护设备；收费/监控/通信等系统设备，论述匹配性与可靠性】"))
    out.append(h2("（三）工程方案"))
    out.append(h3("1. 路线方案比选"))
    out.append(para("【道路专项：至少 2–3 个方案，从技术可行性、工程规模（里程/土石方/桥隧比）、征地拆迁、环境敏感、投资等维度比选，给推荐方案及理由；二级及以上公路在 1:10000 及以上地形图研究】"))
    out.append(h3("2. 路基路面"))
    out.append(para("【待补充：路基压实度、路面结构类型（如沥青混凝土）、排水系统设计】"))
    out.append(h3("3. 桥涵"))
    out.append(para("【待补充：大桥/特大桥、特殊结构桥梁设计方案】"))
    out.append(h3("4. 隧道"))
    out.append(para("【待补充：特长隧道通风、照明、消防、逃生系统】"))
    out.append(h3("5. 交叉工程"))
    out.append(para("【待补充：互通式立交、平面交叉】"))
    out.append(h3("6. 交通工程及沿线设施"))
    out.append(para("【待补充：标志标线、照明、监控、收费系统、服务区；智慧公路预留车路协同接口】"))
    out.append(h3("7. 绿化及环境保护工程"))
    out.append(para("【待补充：绿化、环境保护与生态修复措施】"))
    out.append(h2("（四）用地用海征收补偿（安置）方案"))
    out.append(para("【待补充：征收范围、土地现状、征收目的、补偿方式和标准、安置对象与方式、社会保障、补偿费用；用海用岛利益相关者协调】"))
    out.append(h2("（五）数字化方案"))
    out.append(para("【待补充：数字化应用（技术/设备/工程/建设管理/运维/网络安全），以数字化交付为目的的设计-施工-运维全过程数字化（BIM）】"))
    out.append(h2("（六）建设管理方案"))
    out.append(para("【待补充：组织模式与机构；质量安全方案与验收标准；工期与时序；招标方案（范围/组织形式/方式）；建设管理模式（代建/EPC/全过程咨询）；以工代赈任务】"))

    # 六、项目运营方案
    out.append(h1("六、项目运营方案"))
    out.append(h2("（一）运营模式选择"))
    out.append(para("【待补充：自主/委托第三方运营；道路养护模式（自行/市场化）】"))
    out.append(h2("（二）运营组织方案"))
    out.append(para("【待补充：组织机构、人力资源、培训、合规治理】"))
    out.append(h2("（三）安全保障方案"))
    out.append(para("【待补充：交通事故/恶劣天气/隧道安全等危险因素；安全生产责任制、管理体系、应急预警预案；智慧公路数据安全/网络安全】"))
    out.append(h2("（四）绩效管理方案"))
    out.append(para("【待补充：全生命周期 KPI（PQI 路况、通行效率、事故率、养护成本）；子项目分别确定绩效目标】"))

    # 七、投融资与财务
    out.append(h1("七、项目投融资与财务方案"))
    out.append(h2("（一）投资估算"))
    out.append(para("【道路专项：依据《公路工程估算指标》，含建安费+征拆+其他+预备费；工可阶段静态投资准确度 ±10%；分年度投资计划】"))
    out.append(h2("（二）盈利能力分析"))
    out.append(para("【道路专项：收费公路做财务评价 FIRR/FNPV/投资回收期/贷款偿还期；非收费政府项目做全生命周期资金平衡；资本金注入项目算 FIRR/FNPV】"))
    out.append(h2("（三）融资方案"))
    out.append(para("【待补充：权益性与债务性融资结构及成本；专项债/公司债/PPP 可行性；REITs 盘活路径】"))
    out.append(h2("（四）债务清偿能力分析"))
    out.append(para("【待补充：利息备付率、偿债备付率；是否增加地方支出负担/隐性债务】"))
    out.append(h2("（五）财务可持续性分析"))
    out.append(para("【待补充：财务计划现金流量表，各年净现金流与累计盈余；经营净现金流不足的研究接续方案】"))
    out.append(h2("（六）国民经济评价"))
    out.append(para("【道路专项关键：计算 EIRR、ENPV，采用影子价格（劳动力按当地平均工资 50% 等参数），评价国民经济净贡献，与政府决策结论并列】"))

    # 八、影响效果
    out.append(h1("八、项目影响效果分析"))
    out.append(h2("（一）经济影响分析"))
    out.append(para("【待补充：费用效益或效果；重大项目的宏观/产业/区域经济影响】"))
    out.append(h2("（二）社会影响分析"))
    out.append(para("【待补充：社会调查与公众参与；利益相关者；以工代赈带动就业；减缓负面社会影响；重大项目社会稳定风险评估】"))
    out.append(h2("（三）生态环境影响分析"))
    out.append(para("【待补充：环境生态现状；污染/地灾/防洪/水保/生态修复/生物多样性/敏感区；减缓补偿与减排；衔接环评】"))
    out.append(h2("（四）资源和能源利用效果分析"))
    out.append(para("【待补充：水/能源/再生资源利用；单位产能资源消耗；节能后能耗与能效】"))
    out.append(h2("（五）碳达峰碳中和分析"))
    out.append(para("【待补充：碳排放总量与强度核算，碳控制方案与路径，对双碳目标影响】"))

    # 九、风险
    out.append(h1("九、项目风险管控方案"))
    out.append(h2("（一）风险识别与评价"))
    out.append(para("【待补充：识别需求/建设/运营/融资/财务/经济/社会/环境/数据安全等风险，分析可能性、损失、韧性，判定主要风险】"))
    out.append(h2("（二）风险管控方案"))
    out.append(para("【待补充：针对性防范化解措施；重大项目稳评（风险点/可能性/影响/等级建议）；邻避综合管控】"))
    out.append(h2("（三）风险应急预案"))
    out.append(para("【待补充：重大风险应急处置及演练要求；道路重点：地质复杂、交通量不足、资金到位、工期、征拆阻力】"))

    # 十、结论
    out.append(h1("十、研究结论及建议"))
    out.append(h2("（一）主要研究结论"))
    out.append(para("【待补充：从必要性、要素保障性、工程可行性、运营有效性、财务合理性、影响可持续性、风险可控性七维度简述，给出是否可行结论】"))
    out.append(h2("（二）问题与建议"))
    out.append(para("【待补充：需重点关注的进一步研究解决问题及相关建议】"))

    # 十一、附表附图附件
    out.append(h1("十一、附表、附图和附件"))
    out.append(h2("附表"))
    out.append(para("【主要技术经济指标表；投资估算表（分项）；资金筹措表；国民经济评价指标表；财务评价表（收费公路）；敏感性分析表；用地量表】"))
    out.append(h2("附图"))
    out.append(para("【路线方案示意图（含比选）；路线总体布置图；主要桥隧布置图；交通量预测图】"))
    out.append(h2("附件"))
    out.append(para("【项目建议书及批复；规划依据；用地预审与规划选址意见；环评/水保/稳评专题；地勘资料；专题论证】"))

    # 自查清单
    out.append(h1("附录：道路专项必检清单（成稿后逐项核对）"))
    checks = [
        "适用大纲已明确（通用大纲 vs 参考大纲）",
        "十章结构完整、标题与 304 号文一致",
        "交通量预测已做（四阶段法、特征年、分车型、弹性系数有依据、通道分流已考虑）",
        "技术标准已按 JTG B01 确定（等级/速度/路基宽/车道/荷载/洪水频率）",
        "路线方案比选 ≥2 个方案，含推荐理由与多维比选",
        "工程方案覆盖路基路面、桥涵、隧道、交叉、交通工程及沿线设施",
        "投资估算依据公路工程估算指标，含征拆与预备费，误差 ±10%",
        "国民经济评价已做（EIRR/ENPV，影子价格参数）",
        "收费公路已做财务评价（FIRR/FNPV/回收期/贷款偿还期）",
        "社会稳定风险评估已列（重大项目）",
        "生态环境/水保/双碳衔接已说明",
        "附表（投资估算表、经济/财务评价表、用地量表）齐全",
        "附图（路线比选图、总体布置图）已列",
        "附件（立项批复、规划、用地预审、选址、环评/水保/稳评）已列",
        "缺失信息均用【待补充】占位并汇总至下方清单",
    ]
    for c in checks:
        out.append(f"- [ ] {c}\n")

    out.append(h2("需补充资料清单"))
    out.append(para("【将正文中所有【待补充：……】汇总列示，便于向用户/建设单位索取】\n"))

    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description="生成道路工程可研报告骨架（304号文十章框架）")
    ap.add_argument("--name", default="", help="项目名称，如 'XX 公路改建工程'")
    ap.add_argument("--out", default="", help="输出文件路径；省略则打印到 stdout")
    args = ap.parse_args()

    text = build(args.name)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"已生成骨架：{args.out}（{len(text)} 字符）")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
